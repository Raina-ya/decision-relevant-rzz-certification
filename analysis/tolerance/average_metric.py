"""Average-metric insufficiency for decisions (candidate C7).

Average gate fidelity of the diagonal residual depends only on |Tr E|. It is
invariant under the order-8 group generated by the sign maps
(epsilon, a, b) -> (s1 s2 epsilon, s1 a, s2 b) and by complex conjugation
(epsilon, a, b) -> (-epsilon, -a, -b). The downstream QAOA decision is not
invariant under that group, so equal average fidelity cannot certify a
decision. All numbers produced here are [exact]; the statement is
[theory, draft].
"""

from __future__ import annotations

from cmath import exp
from math import pi, sin
from dataclasses import asdict, dataclass
from itertools import product
import json
from pathlib import Path

from analysis.tolerance.instances import GeneratedDecision
from src.decision import EdgeError, signed_gap


Residual = tuple[float, float, float]


def residual_trace(residual: Residual) -> complex:
    epsilon, a, b = residual
    return sum(
        exp(-0.5j * (epsilon * z1 * z2 + a * z1 + b * z2))
        for z1 in (1, -1)
        for z2 in (1, -1)
    )


def average_gate_fidelity(residual: Residual) -> float:
    """Two-qubit average gate fidelity of exp(-i(eps ZZ + a ZI + b IZ)/2) [exact]."""
    dimension = 4
    process_fidelity = abs(residual_trace(residual)) ** 2 / dimension**2
    return (dimension * process_fidelity + 1.0) / (dimension + 1.0)


def eigenphases(residual: Residual) -> tuple[float, ...]:
    """Eigenphases phi(z) / 2 of E over z in {+1, -1}^2, wrapped to (-pi, pi]."""
    epsilon, a, b = residual
    phases = []
    for z1 in (1, -1):
        for z2 in (1, -1):
            phi = -0.5 * (epsilon * z1 * z2 + a * z1 + b * z2)
            phases.append((phi + pi) % (2 * pi) - pi)
    return tuple(sorted(phases))


def diamond_distance_to_identity(residual: Residual) -> float:
    """Diamond distance between the unitary channels E(.)E^dagger and identity [exact].

    For a unitary with eigenvalues on the unit circle, the distance is
    2 sqrt(1 - d^2) with d the distance from the origin to their convex hull;
    if the smallest arc containing all eigenvalues is ell < pi this equals
    2 sin(ell / 2), otherwise 2.
    """
    phases = sorted(eigenphases(residual))
    gaps = [phases[i + 1] - phases[i] for i in range(len(phases) - 1)]
    gaps.append(2 * pi - (phases[-1] - phases[0]))
    arc = 2 * pi - max(gaps)
    return 2.0 if arc >= pi else 2.0 * sin(arc / 2.0)


def fidelity_orbit(residual: Residual) -> tuple[Residual, ...]:
    """All images of a residual under the order-8 fidelity-preserving group."""
    epsilon, a, b = residual
    images = set()
    for s1, s2, conj in product((1, -1), repeat=3):
        image = (conj * s1 * s2 * epsilon, conj * s1 * a, conj * s2 * b)
        images.add(tuple(round(value, 12) + 0.0 for value in image))
    return tuple(sorted(images))


@dataclass(frozen=True, slots=True)
class Witness:
    instance_id: str
    margin: float
    average_fidelity: float
    harmless_residual: Residual
    harmless_gamma: float
    harmful_residual: Residual
    harmful_gamma: float
    evidence: str = "[exact]"


def _decision(record: dict) -> GeneratedDecision:
    values = dict(record)
    values["edges"] = tuple(tuple(edge) for edge in values["edges"])
    return GeneratedDecision(**values)


def find_witness(record: dict, grid: tuple[float, ...]) -> Witness | None:
    """Highest-fidelity grid residual whose orbit contains a harmless and a harmful member.

    The same residual is applied at both decision angles (angle-independent
    residual), which is the weakest case for this argument.
    """
    decision = _decision(record)
    instance, first, second = decision.objects()
    edges = len(instance.edges)
    best: Witness | None = None
    for residual in product(grid, repeat=3):
        fidelity = average_gate_fidelity(residual)
        if best is not None and fidelity <= best.average_fidelity:
            continue
        gammas = []
        for image in fidelity_orbit(residual):
            errors = tuple(EdgeError(*image) for _ in range(edges))
            gammas.append((signed_gap(instance, first, second, errors), image))
        high, low = max(gammas), min(gammas)
        if high[0] >= decision.margin and low[0] < 0.0:
            best = Witness(
                decision.instance_id,
                decision.margin,
                fidelity,
                high[1],
                high[0],
                low[1],
                low[0],
            )
    return best


def run(family_path: Path, output: Path, half_width: float = 0.6, step: float = 0.05) -> dict:
    family = json.loads(family_path.read_text(encoding="utf-8"))
    count = round(half_width / step)
    grid = tuple(step * index for index in range(-count, count + 1))
    results = []
    for record in family["instances"]:
        witness = find_witness(record, grid)
        results.append(
            {"instance_id": record["instance_id"], "witness": asdict(witness) if witness else None}
        )
    payload = {
        "status": "unlocked-development",
        "evidence": "[exact]",
        "statement": "theory/average_metric_insufficiency.md",
        "grid": {"half_width": half_width, "step": step},
        "family": str(family_path.as_posix()),
        "results": results,
    }
    output.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8", newline="\n")
    return payload


